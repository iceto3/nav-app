// Regenerate the <link rel="modulepreload"> block in index.html and editor/index.html from the import graph of app.js.
// Without it the browser discovers ES modules level by level (one round trip per import depth); with it all modules
// are fetched in parallel with the vendor scripts, so loading is no slower than the old single app.js.
// usage: node scripts/gen-preload.mjs [--check]   (--check: exit 1 if the HTML is out of date; used by tests)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const START = '<!-- modulepreload:start (generated by scripts/gen-preload.mjs) -->', END = '<!-- modulepreload:end -->';

/** Depth-first import graph from app.js; returns root-relative URLs with their ?v= query. */
export function moduleUrls() {
  const seen = new Set(), out = [];
  const visit = (rel) => {
    const file = rel.split('?')[0]; if (seen.has(file)) return; seen.add(file);
    const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    for (const m of src.matchAll(/^\s*(?:import|export)\s[^'"]*?['"]([^'"]+)['"]/gm)) {
      if (!m[1].startsWith('.')) continue;
      const q = m[1].includes('?') ? '?' + m[1].split('?')[1] : '';
      const abs = path.posix.normalize(path.posix.join(path.posix.dirname(file), m[1].split('?')[0]));
      if (!seen.has(abs)) { out.push(abs + q); visit(abs + q); }
    }
  };
  visit('app.js');
  return out;
}

const block = indent => [START, ...moduleUrls().map(u => `<link rel="modulepreload" href="${u}">`), END].join('\n' + indent);
let stale = false;
for (const f of ['index.html', 'editor/index.html']) {
  const p = path.join(ROOT, f), html = fs.readFileSync(p, 'utf8');
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
  const next = re.test(html) ? html.replace(re, block('')) : html.replace(/(<script src="vendor\/maplibre-gl\.js"><\/script>)/, block('') + '\n$1');
  if (next !== html) { stale = true; if (!process.argv.includes('--check')) fs.writeFileSync(p, next); }
}
if (process.argv.includes('--check')) { if (stale) { console.error('modulepreload block out of date: run node scripts/gen-preload.mjs'); process.exit(1); } console.log('modulepreload up to date'); }
else console.log('modulepreload:', moduleUrls().length, 'modules');
